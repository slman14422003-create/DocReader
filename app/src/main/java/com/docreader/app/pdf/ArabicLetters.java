    /** الحروف الشمسية (تُدغم فيها لام "ال"). */
    static final String SUN = "\u062A\u062B\u062F\u0630\u0631\u0632\u0633\u0634\u0635\u0636\u0637\u0638\u0644\u0646";
    /** حروف الاستعلاء (تفخيم دائم). */
    static final String HEAVY = "\u062E\u0635\u0636\u063A\u0637\u0642\u0638";
    /** حروف الإطباق. */
    static final String EMPHATIC = "\u0635\u0636\u0637\u0638";
    /** حروف القلقلة (قُطب جد). */
    static final String QALQALA = "\u0642\u0637\u0628\u062C\u062F";
    /** حروف الصفير. */
    static final String SAFIR = "\u0635\u0632\u0633";
    /** حروف لا تتصل بما بعدها. */
    private static final String NON_JOINING = "\u0627\u062F\u0630\u0631\u0632\u0648\u0621";

    // ------------------------------------------------------------------ النموذج

    static final class Letter {
        final char ch;
        /** اسم الحرف مشكولًا للعرض (بَاء). */
        final String name;
        /** صيغة النطق للمحرك (بَاء / جِيمْ): سكون على الآخر ما عدا الهمزة. */
        final String spoken;
        /** تقريب بحروف لاتينية. */
        final String latin;
        final String ipa;
        /** مجموعة المخرج: الجوف / الحلق / اللسان / الشفتان. */
        final String group;
        final String makhraj;
        final String sifat;
        final String tip;
        /** مثال أول الكلمة / وسطها / آخرها (فارغ لو لا يوجد). */
        final String[] examples;

        Letter(char ch, String name, String latin, String ipa, String group, String makhraj, String sifat,
               String tip, String ex1, String ex2, String ex3) {
            this.ch = ch;
            this.name = name;
            this.spoken = spokenOf(name);
            this.latin = latin;
            this.ipa = ipa;
            this.group = group;
            this.makhraj = makhraj;
            this.sifat = sifat;
            this.tip = tip;
            this.examples = new String[]{ex1, ex2, ex3};
        }

        boolean isSun() {
            return SUN.indexOf(ch) >= 0;
        }

        boolean isHeavy() {
            return HEAVY.indexOf(ch) >= 0;
        }

        boolean isEmphatic() {
            return EMPHATIC.indexOf(ch) >= 0;
        }

        boolean hasQalqala() {
            return QALQALA.indexOf(ch) >= 0;
        }

        boolean isSafir() {
            return SAFIR.indexOf(ch) >= 0;
        }

        boolean joinsNext() {
            return NON_JOINING.indexOf(ch) < 0;
        }
    }

    /** علامة أو حالة خاصة (حركة، شدّة، تنوين، مدّ، تاء مربوطة...). */
    static final class Special {
        final String symbol;
        final String title;
        final String how;
        final String example;

        Special(String symbol, String title, String how, String example) {
            this.symbol = symbol;
            this.title = title;
            this.how = how;
            this.example = example;
        }
    }

    private static final List<Letter> LETTERS = new ArrayList<>();
    private static final Map<Character, Letter> BY_CHAR = new HashMap<>();
    private static final List<Special> SPECIALS = new ArrayList<>();

    private static String spokenOf(String name) {
        char last = name.charAt(name.length() - 1);
        if (last == '\u0621' || last == '\u0629') return name;
        return name + SUKUN;
    }

    private static void L(char ch, String name, String latin, String ipa, String group, String makhraj,
                          String sifat, String tip, String ex1, String ex2, String ex3) {
        Letter l = new Letter(ch, name, latin, ipa, group, makhraj, sifat, tip, ex1, ex2, ex3);
        LETTERS.add(l);
        BY_CHAR.put(ch, l);
    }

    private static void S(String symbol, String title, String how, String example) {
        SPECIALS.add(new Special(symbol, title, how, example));
    }

