    /** أشكال الحرف: منفصل / أول / وسط / آخر (بالتطويل). */
    static String forms(Letter l) {
        String c = String.valueOf(l.ch);
        if (l.ch == '\u0621') return c;
        String isolated = c;
        String initial = l.joinsNext() ? c + "\u0640" : c;
        String medial = l.joinsNext() ? "\u0640" + c + "\u0640" : "\u0640" + c;
        String fin = "\u0640" + c;
        return isolated + "     " + initial + "     " + medial + "     " + fin;
    }

    /** الحرف مع الحركات: بَ بِ بُ بْ بّ (الألف والهمزة لهما شكل خاص). */
    static String withHarakat(Letter l) {
        char c = l.ch;
        if (c == '\u0627') return "بَا     بِي     بُو";
        if (c == '\u0621') return "أَ     إِ     أُ     أْ";
        return c + "" + FATHA + "     " + c + KASRA + "     " + c + DAMMA + "     " + c + SUKUN + "     " + c + SHADDA + FATHA;
    }

    /** "الْبَاءِ" / "الثَّاءِ" : اسم الحرف بأل التعريف مجرورًا (بعد كلمة "حرف"). */
    static String articleGenitive(Letter l) {
        String n = l.name;
        char first = n.charAt(0);
        StringBuilder sb = new StringBuilder("\u0627\u0644");
        if (SUN.indexOf(first) >= 0) {
            sb.append(first).append(SHADDA).append(n, 1, n.length());
        } else {
            sb.append(SUKUN).append(n);
        }
        return sb.append(KASRA).toString();
    }

    /** ما يُقرأ صوتيًا لدرس الحرف: اسمه، ثم مقاطعه بالحركات، ثم أمثلة. */
    static String lessonText(Letter l) {
        StringBuilder sb = new StringBuilder();
        sb.append("حَرْفُ ").append(articleGenitive(l)).append(". ");
        if (l.ch == '\u0627') {
            sb.append("مَدٌّ بِالْأَلِفِ: بَا، مَا، سَا. ");
        } else if (l.ch == '\u0621') {
            sb.append("الْهَمْزَةُ مَعَ الْحَرَكَاتِ: أَ، إِ، أُ، أَأْ. ");
        } else {
            char c = l.ch;
            sb.append("مَعَ الْحَرَكَاتِ: ")
                    .append(c).append(FATHA).append("، ")
                    .append(c).append(KASRA).append("، ")
                    .append(c).append(DAMMA).append("، ")
                    .append("أَ").append(c).append(SUKUN).append(". ");
        }
        boolean any = false;
        StringBuilder ex = new StringBuilder();
        for (String e : l.examples) {
            if (e == null || e.isEmpty()) continue;
            if (any) ex.append("، ");
            ex.append(e);
            any = true;
        }
        if (any) sb.append("أَمْثِلَةٌ: ").append(ex).append('.');
        return sb.toString();
    }

    /** شرح المخرج والصفات والتنبيه للاستماع. */
    static String explainText(Letter l) {
        StringBuilder sb = new StringBuilder();
        sb.append("مَخْرَجُ حَرْفِ ").append(articleGenitive(l)).append(": ").append(l.makhraj).append(' ');
        sb.append("صِفَاتُهُ: ").append(l.sifat).append(' ');
        sb.append("تَنْبِيهٌ: ").append(l.tip);
        return sb.toString();
    }

    static String specialText(Special s) {
        return s.title + ". " + s.how + " أَمْثِلَةٌ: " + s.example.replace('=', ' ');
    }

    /** ملخص نوع الحرف للعرض. */
    static String kindLine(Letter l) {
        List<String> k = new ArrayList<>();
        if (l.ch == '\u0627') {
            k.add("حرف مدّ");
        } else if (l.ch == '\u0621') {
            k.add("همزة قطع");
        } else {
            k.add(l.isSun() ? "شمسي (تُدغم فيه لام ال)" : "قمري (تظهر معه لام ال)");
        }
        if (l.isEmphatic()) k.add("مفخّم مطبق");
        else if (l.isHeavy()) k.add("مفخّم");
        else if (l.ch == '\u0631' || l.ch == '\u0644' || l.ch == '\u0627') k.add("يُفخّم ويُرقّق بحسب موضعه");
        else k.add("مرقّق");
        if (l.hasQalqala()) k.add("قلقلة");
        if (l.isSafir()) k.add("صفير");
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < k.size(); i++) {
            if (i > 0) sb.append(" ، ");
            sb.append(k.get(i));
        }
        return sb.toString();
    }
