    /** يوحّد أشكال الحرف: أ إ آ ٱ -> ا ، ؤ ئ -> ء. */
    private static char canonical(char c) {
        switch (c) {
            case '\u0623':
            case '\u0625':
            case '\u0622':
            case '\u0671':
                return '\u0627';
            case '\u0624':
            case '\u0626':
                return '\u0621';
            default:
                return c;
        }
    }

    static Letter byChar(char c) {
        return BY_CHAR.get(canonical(c));
    }

    /** اسم الحرف الجاهز للمحرك (بَاء / جِيمْ)، أو null لو ليس حرفًا عربيًا معروفًا. */
    static String spokenName(char c) {
        if (c == '\u0649') return "أَلِفْ مَقْصُورَة";
        if (c == '\u0629') return "تَاءْ مَرْبُوطَة";
        Letter l = byChar(c);
        return l == null ? null : l.spoken;
    }

    /** "عم" أو "ع.م" -> "عَيْنْ مِيمْ": كل حرف باسمه. الفواصل والنقاط تُتجاهل. */
    static String spell(String letters) {
        if (letters == null || letters.isEmpty()) return "";
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < letters.length(); i++) {
            String n = spokenName(letters.charAt(i));
            if (n == null) continue;
            if (sb.length() > 0) sb.append(' ');
            sb.append(n);
        }
        return sb.toString();
    }

    static boolean isSun(char c) {
        return SUN.indexOf(canonical(c)) >= 0;
    }

    static boolean isHeavy(char c) {
        return HEAVY.indexOf(canonical(c)) >= 0;
    }

